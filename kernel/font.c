void gfx_glyph(struct gfx_surface *s, int64_t x, int64_t y, unsigned char ch,
               uint32_t fg, uint32_t bg, unsigned scale) {
    if (!s || !s->pixels || !scale || scale > 4 || x < -24 || y < -36 ||
        x >= s->width || y >= s->height) return;
    if (ch < 32 || ch > 126) ch = '?';
    gfx_rect(s, x, y, 6 * scale, 9 * scale, bg);
    for (unsigned col = 0; col < 5; col++)
        for (unsigned row = 0; row < 7; row++)
            if (font[ch - 32][col] & (1U << row))
                gfx_rect(s, x + col * scale, y + row * scale, scale, scale, fg);
}
